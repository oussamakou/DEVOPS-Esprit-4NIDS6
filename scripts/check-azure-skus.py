"""Check subscription SKU restrictions before preparing a Cloud Shell plan.

This checks listed eligibility, not live allocation capacity. Quota and the actual
Terraform plan must still be reviewed before applying.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess
import sys


def validate_sku(skus, size, location):
    matches = [sku for sku in skus if sku.get("name", "").casefold() == size.casefold()]
    if len(matches) != 1:
        raise ValueError(f"{size} was not uniquely listed for {location}; choose another size or region")
    sku = matches[0]
    for restriction in sku.get("restrictions", []):
        if restriction.get("type", "").casefold() != "location":
            continue  # A zone-only restriction does not prohibit an unzoned VM.
        locations = restriction.get("values", []) + restriction.get("restrictionInfo", {}).get("locations", [])
        if not locations or location.casefold() in [value.casefold() for value in locations]:
            reason = restriction.get("reasonCode", "subscription restriction")
            raise ValueError(f"{size} is restricted in {location}: {reason}")
    return sku


def fetch_skus(location, sizes):
    if not all(re.fullmatch(r"[A-Za-z0-9_]+", size) for size in sizes):
        raise ValueError("VM size names must contain only letters, digits and underscores")
    query = "[?" + " || ".join(f"name=='{size}'" for size in sizes) + "]"
    print(f"Querying Azure VM eligibility in {location} for {', '.join(sizes)} (timeout: 180 seconds)...", flush=True)
    try:
        # One catalogue request for both VMs; the old loop downloaded it twice.
        raw = subprocess.check_output(["az", "vm", "list-skus", "--location", location,
                                       "--resource-type", "virtualMachines", "--all",
                                       "--query", query, "--output", "json"], text=True, timeout=180)
    except subprocess.TimeoutExpired as error:
        raise ValueError("Azure VM eligibility query timed out after 180 seconds; no resource plan was generated by this attempt") from error
    return json.loads(raw)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report-only", action="store_true", help="Discover eligible/restricted sizes without preparing a deployment")
    parser.add_argument("location")
    parser.add_argument("sizes", nargs="+")
    args = parser.parse_args()
    location, sizes = args.location, args.sizes
    try:
        skus = fetch_skus(location, sizes)
    except (ValueError, subprocess.CalledProcessError) as error:
        raise SystemExit(str(error)) from error
    # Preserve returned restrictions even when validation fails.
    output = Path(__file__).resolve().parents[1] / ".tools/azure-skus.json"
    output.parent.mkdir(exist_ok=True)
    output.write_text(json.dumps(skus, indent=2), encoding="utf-8")
    failures = []
    eligible = 0
    for size in sizes:
        try:
            sku = validate_sku(skus, size, location)
        except ValueError as error:
            failures.append(str(error))
            print(f"RESTRICTED / UNLISTED: {error}", flush=True)
            continue
        eligible += 1
        capabilities = {item["name"]: item["value"] for item in sku.get("capabilities", [])}
        print(f"Eligible SKU: {size}; family={sku.get('family')}; vCPUs={capabilities.get('vCPUs')}; memoryGB={capabilities.get('MemoryGB')}", flush=True)
    if args.report_only:
        print(f"Discovery complete: {eligible} eligible, {len(failures)} restricted/unlisted. No Terraform inputs, plan or Azure resources created.")
        return
    if failures:
        raise SystemExit(f"Preparation blocked: {len(failures)} requested VM size(s) are restricted or unlisted. All requested sizes were checked.")
    print("SKU eligibility checked. Review remaining regional/family quota and the plan; live capacity is checked by Azure during deployment.")


if __name__ == "__main__":
    main()
